const dicts: Record<Lang, Record<Key, string>> = { en, zh };

type T = (key: Key, vars?: Record<string, string | number>) => string;

const I18nContext = createContext<{ lang: Lang; t: T; setLang: (l: Lang) => void } | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("trove.lang");
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const value = useMemo(() => {
    const t: T = (key, vars) => {
      let s = dicts[lang][key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    };
    const setLang = (l: Lang) => {
      setLangState(l);
      document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
      try {
        localStorage.setItem("trove.lang", l);
      } catch {
        /* ignore */
      }
    };
    return { lang, t, setLang };
  }, [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside provider");
  return ctx;
}

export type { Key as I18nKey };
